"""rapture-recomp driver.

    python -m recomp CONFIG --game-dir DIR --out OUTDIR [--modules a.dll,b.dll] [--limit N]

Reads the game config (module list, guest bases), loads the user's original
modules from DIR, rebases them, resolves imports between them, discovers and
translates functions, and writes into OUTDIR:

    <module>.bin   rebased memory image (IAT already filled)
    funcs.h        prototypes of every generated function
    code_NNN.c     translated functions
    dispatch.c     function table, import table, module table
    report.txt     statistics and every unsupported instruction

OUTDIR is a build directory on the user's machine: it must never be committed.
"""
from __future__ import annotations

import argparse
import os
import struct
import sys
import tomllib

from . import cfg, pe
from .x86c import Translator, fname

THUNK_BASE = 0xFFF00000


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="recomp")
    ap.add_argument("config")
    ap.add_argument("--game-dir", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--modules", help="comma-separated subset of modules to translate (all are loaded)")
    ap.add_argument("--limit", type=int, default=0, help="translate at most N functions per module (debug)")
    ap.add_argument("--chunk", type=int, default=400, help="functions per generated .c file")
    a = ap.parse_args(argv)

    with open(a.config, "rb") as fh:
        conf = tomllib.load(fh)
    os.makedirs(a.out, exist_ok=True)

    mods: list[pe.Module] = []
    for m in conf["module"]:
        path = os.path.join(a.game_dir, m["file"])
        mods.append(pe.load(path, int(m["base"], 0)))
    by_name = {m.name: m for m in mods}

    # -- imports: other guest modules resolve statically, the rest get thunks
    thunks: dict[tuple, int] = {}
    import_rows = []
    for m in mods:
        for im in m.imports:
            target_mod = by_name.get(im.dll)
            if target_mod is not None:
                t = target_mod.exports.get(im.name) if im.name else target_mod.exports_ord.get(im.ordinal)
                if t is None:
                    raise SystemExit(f"{m.name}: unresolved import {im.dll}!{im.name or im.ordinal}")
            else:
                key = (im.dll, im.name, im.ordinal)
                if key not in thunks:
                    thunks[key] = THUNK_BASE + 16 * len(thunks)
                t = thunks[key]
            struct.pack_into("<I", m.image, im.slot - m.base, t)
            import_rows.append((im.slot, im.dll, im.name, im.ordinal or 0, t))

    for m in mods:
        with open(os.path.join(a.out, m.name + ".bin"), "wb") as fh:
            fh.write(m.image)

    selected = set(x.strip().lower() for x in a.modules.split(",")) if a.modules else set(by_name)
    extra = {k.lower(): [int(x, 0) for x in v] for k, v in conf.get("extra_functions", {}).items()}

    funcs: dict[int, cfg.Function] = {}
    report = []
    for m in mods:
        if m.name not in selected:
            continue
        fs = cfg.discover(m, extra.get(m.name, []))
        if a.limit:
            fs = dict(sorted(fs.items())[: a.limit])
        report.append(f"{m.name}: {len(fs)} functions, {sum(len(f.insns) for f in fs.values())} instructions, "
                      f"{sum(len(f.jump_tables) for f in fs.values())} jump tables")
        funcs.update(fs)

    known = set(funcs)
    bodies = []
    unimpl = []
    for e in sorted(funcs):
        t = Translator(funcs[e], known)
        bodies.append(t.translate())
        unimpl.extend(t.unimpl)
        for b in funcs[e].bad:
            unimpl.append(f"{e:#x}: {b}")

    with open(os.path.join(a.out, "funcs.h"), "w") as fh:
        fh.write("/* generated by rapture-recomp: do not edit, do not commit */\n#pragma once\n#include \"recomp.h\"\n")
        for e in sorted(funcs):
            fh.write(f"void {fname(e)}(CPU *c);\n")
    old = [f for f in os.listdir(a.out) if f.startswith("code_") and f.endswith(".c")]
    for f in old:
        os.remove(os.path.join(a.out, f))
    for k in range(0, len(bodies), a.chunk):
        with open(os.path.join(a.out, f"code_{k // a.chunk:03d}.c"), "w") as fh:
            fh.write("/* generated by rapture-recomp: do not edit, do not commit */\n#include \"funcs.h\"\n\n")
            fh.write("\n\n".join(bodies[k:k + a.chunk]))
            fh.write("\n")

    with open(os.path.join(a.out, "dispatch.c"), "w") as fh:
        fh.write("/* generated by rapture-recomp: do not edit, do not commit */\n#include \"funcs.h\"\n\n")
        fh.write("const rc_func_entry rc_func_table[] = {\n")
        for e in sorted(funcs):
            fh.write(f"  {{0x{e:08x}u, {fname(e)}}},\n")
        fh.write("  {0xFFFFFFFFu, 0}\n};\n")
        fh.write(f"const uint32_t rc_func_count = {len(funcs)};\n\n")
        fh.write("const rc_import rc_import_table[] = {\n")
        for (dll, name, ordn), t in sorted(thunks.items(), key=lambda kv: kv[1]):
            nm = f'"{name}"' if name else "0"
            fh.write(f'  {{0x{t:08x}u, "{dll}", {nm}, {ordn or 0}u, 0x{t:08x}u}},\n')
        fh.write("  {0, 0, 0, 0, 0}\n};\n")
        fh.write(f"const uint32_t rc_import_count = {len(thunks)};\n\n")
        fh.write("const rc_module rc_module_table[] = {\n")
        for m in mods:
            fh.write(f'  {{"{m.name}", "{m.name}.bin", 0x{m.base:08x}u, 0x{m.size:x}u}},\n')
        fh.write("};\n")
        fh.write(f"const uint32_t rc_module_count = {len(mods)};\n")

    report.append(f"system imports (thunks): {len(thunks)}")
    report.append(f"unsupported instructions: {len(unimpl)}")
    with open(os.path.join(a.out, "report.txt"), "w") as fh:
        fh.write("\n".join(report) + "\n\n" + "\n".join(unimpl) + "\n")
    print("\n".join(report))
    return 0


if __name__ == "__main__":
    sys.exit(main())
